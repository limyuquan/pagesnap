/**
 * Core capture data model shared by the service worker (A), the compositor (A) and the editor (B, C).
 *
 * Units, used consistently everywhere:
 * - **CSS px**: page layout pixels, as the captured page saw them.
 * - **image px**: pixels of the stitched output image. `image px = CSS px * session.dpr`.
 *   Annotation shapes are stored in image px too (see `annotations.ts`).
 * - **bitmap px**: pixels of one stored slice PNG (what `captureVisibleTab` returned). Slices are
 *   placed 1:1 into the image, so bitmap px and image px have the same scale.
 *
 * Changing anything in this file needs a note in docs/CONTRACTS.md (see "Changing a contract").
 */

/** Axis-aligned rectangle. The unit is stated wherever the type is used. */
export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface Point {
  x: number;
  y: number;
}

export interface Size {
  w: number;
  h: number;
}

/** Opaque capture session id. Generated by `newSessionId()` in `ids.ts`. URL-safe. */
export type SessionId = string;

/**
 * Lifecycle of a capture session.
 * - `capturing`: slices are still being written. `image`, `slices` and `layout` may still change.
 * - `ready`: every planned slice is stored and `layout` is final.
 * - `partial`: the capture stopped early (`error` says why) but at least one slice is stored and
 *   `layout` is final for what was captured. The editor opens it normally and shows a notice.
 * - `error`: nothing usable was captured (`slices` is empty). The editor shows `error.message`.
 *
 * `ready`, `partial` and `error` are final: a session never leaves them.
 */
export type SessionStatus = 'capturing' | 'ready' | 'partial' | 'error';

/** Final statuses. */
export const FINAL_STATUSES: readonly SessionStatus[] = ['ready', 'partial', 'error'];

export function isFinalStatus(status: SessionStatus): boolean {
  return status !== 'capturing';
}

/** What the capture tried to grab. v0.1 only produces `full` (and `visible` as a fallback). */
export type CaptureMode = 'full' | 'visible';

export type CaptureErrorCode =
  /** The page can't be scripted (chrome://, Web Store, PDF viewer, ...). */
  | 'RESTRICTED'
  /** The tab was closed, navigated, deactivated or its window minimised mid-capture. */
  | 'TAB_CHANGED'
  /** The user pressed Esc in the page. */
  | 'ABORTED_BY_USER'
  /** The page fights programmatic scrolling. */
  | 'SCROLL_JACKED'
  /** `visualViewport.scale !== 1`: only the pinch-zoomed area would be captured. */
  | 'PINCH_ZOOM'
  /** Slice scale (bitmap width / viewport width) changed mid-capture, e.g. moved to another monitor. */
  | 'SCALE_CHANGED'
  /** `captureVisibleTab` kept failing, e.g. the rate limit retries were exhausted. */
  | 'CAPTURE_FAILED'
  /** The service worker was terminated mid-capture and the session was found unfinished. */
  | 'INTERRUPTED'
  /** The capture couldn't be written to IndexedDB (disk full, quota). */
  | 'STORAGE_FAILED'
  | 'INTERNAL';

export interface CaptureError {
  code: CaptureErrorCode;
  /** Human-readable, short, safe to show in the UI as is. */
  message: string;
}

export type CaptureWarningCode =
  /** The page was taller than `settings.capture.maxCssHeight` and was cut off. */
  | 'TRUNCATED'
  /** Only the visible area was captured (fallback for restricted pages). */
  | 'VISIBLE_ONLY'
  /**
   * Informational, not a problem: an inner scroll container was captured and expanded in place.
   * Listed in `INFO_WARNING_CODES`; UIs shouldn't present it as a warning.
   */
  | 'INNER_SCROLLER'
  /**
   * The page changed while it was captured in a way the capture could not absorb, so a seam may be
   * misaligned. Growth that was followed or re-anchored is not reported.
   */
  | 'HEIGHT_CHANGED'
  /** Some images were still loading when their slice was taken. */
  | 'IMAGES_PENDING'
  /**
   * The page couldn't be scrolled at all (scrolling locked, typically by a cookie wall or dialog),
   * so one screen was captured.
   */
  | 'NOT_SCROLLABLE';

/** Warning codes that are informational only (never shown as a warning). */
export const INFO_WARNING_CODES: readonly CaptureWarningCode[] = ['INNER_SCROLLER'];

export interface CaptureWarning {
  code: CaptureWarningCode;
  message: string;
}

/**
 * Where the scroll target sat and what it covered, in CSS px of the top-level viewport.
 * Reported by the agent on every step (see `protocol.ts`).
 */
export interface TargetGeometry {
  kind: 'document' | 'element';
  /** The scroller's visible box in viewport CSS px. For `document` it is the whole viewport. */
  clientRect: Rect;
  /** Scroll offsets the capture covers, CSS px. Reverse-scrollers are already normalised. */
  range: { x0: number; x1: number; y0: number; y1: number };
  /** Full content size of the target, CSS px (what the output expands to). */
  content: Size;
}

/**
 * One `captureVisibleTab` screenshot. The PNG Blob lives in the `slices` IDB store under
 * `[sessionId, index]`; this metadata lives in `CaptureSession.slices`.
 */
export interface SliceMeta {
  /** 0-based, in capture order. */
  index: number;
  /** Actual scroll offset of the target when the slice was taken (read back, may be fractional), CSS px. */
  scroll: Point;
  /**
   * Where the slice goes in the output, CSS px in the same space as `scroll` (so `place - range.x0/y0`
   * is the output offset). Differs from `scroll` when content above the slice grew or shrank during
   * the capture and the slice was re-anchored to the previous seam. Absent = `scroll`.
   */
  place?: Point;
  /** Pixel size of the stored PNG. */
  bitmap: Size;
  /** Target geometry at the moment of the slice. */
  target: TargetGeometry;
  /** Epoch ms. */
  capturedAt: number;
}

/**
 * Draw `src` (bitmap px of slice `slice`) at `dest` (image px) at 1:1 scale.
 * Slices are never scaled when placed; the compositor asserts a constant scale per session.
 */
export interface Placement {
  slice: number;
  src: Rect;
  dest: Point;
}

/** A solid fill in image px, e.g. a side rail continued below an expanded inner scroller. */
export interface FillRect {
  rect: Rect;
  color: string;
}

/**
 * How to build the base image from slices. This is the only thing anyone needs to reproduce the
 * captured pixels: fill `background`, then every `fills` entry, then draw `parts` **in array order**
 * (later parts overwrite earlier ones where they overlap). `shared/composite.ts` implements exactly
 * this; both the display tiles (A) and the export worker (B) go through it.
 */
export interface BaseLayout {
  /** Equals `CaptureSession.image`. */
  size: Size;
  background: string;
  fills: FillRect[];
  parts: Placement[];
}

/**
 * A capture session: the manifest of one capture. Stored in the `sessions` IDB store (key `id`).
 * Written by the service worker (A). Read-only for everyone else.
 */
export interface CaptureSession {
  /** Schema version of this record. */
  v: 1;
  id: SessionId;
  /** URL and title of the captured tab at capture start. */
  url: string;
  title: string;
  /** Epoch ms. */
  createdAt: number;
  /** Epoch ms of the last write. */
  updatedAt: number;
  mode: CaptureMode;
  status: SessionStatus;
  /** Set for `partial` and `error`, `null` otherwise. */
  error: CaptureError | null;
  warnings: CaptureWarning[];
  /** Slices stored so far vs. estimated total. `total` may grow if the page grows. */
  progress: { done: number; total: number };
  /** Visible viewport of the tab, CSS px, measured after scrollbars were hidden. */
  viewport: Size;
  /**
   * Image px per CSS px, measured as `slice bitmap width / viewport.w` (handles DPR, browser zoom and
   * emulation). Not `window.devicePixelRatio`. Use it to convert CSS-px tool sizes to image px.
   */
  dpr: number;
  /** Output size in CSS px. */
  css: Size;
  /** Output size in image px (`round(css * dpr)`). Final once the status is final. */
  image: Size;
  slices: SliceMeta[];
  /** Final once the status is final. Empty `parts` while `capturing` is allowed. */
  layout: BaseLayout;
  /** Total bytes of the stored slice PNGs (for retention). Absent on older records. */
  bytes?: number;
}

/**
 * One display tile of the base image (image px). Tiles are produced by the compositor (A) for the
 * on-screen viewport. They cover `session.image` exactly, don't overlap, and are listed row-major
 * (top to bottom, then left to right). Each side is at most `DISPLAY_TILE_MAX_SIDE`.
 */
export interface TileMeta {
  index: number;
  rect: Rect;
}
