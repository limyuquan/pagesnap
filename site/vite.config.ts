import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import tailwindcss from '@tailwindcss/vite';
import { defineConfig, type Plugin } from 'vite';

/**
 * The project website (static, `site/`). It reuses the extension's toolchain and its real editor:
 * the demo imports `src/editor/**` through the `@/` alias, and `wxt/browser` resolves to a small
 * in-memory stand-in (`src/demo/browserShim.ts`), since a web page has no extension APIs.
 *
 * `SITE_BASE` sets the public base path (GitHub Pages project sites live under `/<repo>/`).
 */
const r = (p: string) => fileURLToPath(new URL(p, import.meta.url));

/** Absolute URL the site is published at (canonical link, Open Graph). */
const SITE_URL = process.env.SITE_URL ?? 'https://limyuquan.github.io/pagesnap/';

/**
 * The extension's toolbar icons (`public/icon/*.png`, generated by scripts/ui-icons.mjs) double as
 * the site's favicon and the demo's toolbar button. Serve and emit them from there rather than
 * keeping copies that could drift.
 */
function extensionIcons(): Plugin {
  const dir = r('../public/icon');
  let base = '/';
  return {
    name: 'pagesnap-extension-icons',
    configResolved(config) {
      base = config.base;
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const m = /^\/(?:.*\/)?icon\/(\d+\.png)$/.exec(req.url?.split('?')[0] ?? '');
        if (!m?.[1]) return next();
        try {
          res.setHeader('Content-Type', 'image/png');
          res.end(readFileSync(join(dir, m[1])));
        } catch {
          next();
        }
      });
    },
    generateBundle() {
      for (const f of readdirSync(dir)) {
        if (f.endsWith('.png')) {
          this.emitFile({
            type: 'asset',
            fileName: `icon/${f}`,
            source: readFileSync(join(dir, f)),
          });
        }
      }
    },
    // Vite rebases public files in index.html, but these live outside `publicDir`.
    transformIndexHtml: (html) =>
      html.replaceAll('%SITE_URL%', SITE_URL).replaceAll('"/icon/', `"${base}icon/`),
  };
}

export default defineConfig({
  root: r('.'),
  base: process.env.SITE_BASE ?? '/',
  publicDir: r('./public'),
  plugins: [tailwindcss(), extensionIcons()],
  resolve: {
    alias: [
      { find: 'wxt/browser', replacement: r('./src/demo/browserShim.ts') },
      { find: /^@\//, replacement: `${r('../src')}/` },
    ],
  },
  worker: { format: 'es' },
  server: { port: 5181, strictPort: false, fs: { allow: [r('..')] } },
  preview: { port: 4181 },
  build: {
    outDir: r('./dist'),
    emptyOutDir: true,
    target: 'es2022',
    assetsInlineLimit: 0,
    reportCompressedSize: true,
  },
});
